import { Router } from 'express';
import { body } from 'express-validator';
import { register, login, logout, refresh, me, changePassword } from '../controllers/authController.js';
import { listSchedules, createSchedule, updateSchedule, deleteSchedule, scheduleAction } from '../controllers/scheduleController.js';
import { listDoses, doseAction, adherence, materializeToday } from '../controllers/doseController.js';
import { myPatients, adminOverview, adminUsers, approveDoctor, connectPatient } from '../controllers/userController.js';
import Medicine from '../models/Medicine.js';
import { authenticate, authorize } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';

const router = Router();
router.get('/health', (req,res)=>res.json({ success:true, message:'MediTrack API online', data:{ status:'ONLINE', version:'1.0.0' } }));
router.post('/auth/register', [body('name').trim().notEmpty(), body('email').isEmail().normalizeEmail(), body('password').isLength({ min:8 }), body('role').optional().isIn(['DOCTOR','PATIENT','CAREGIVER'])], validate, register);
router.post('/auth/login', [body('email').isEmail(), body('password').notEmpty()], validate, login);
router.post('/auth/refresh', refresh); router.post('/auth/logout', logout);
router.get('/auth/me', authenticate, me); router.patch('/auth/change-password', authenticate, [body('newPassword').isLength({ min:8 })], validate, changePassword);
router.get('/schedules', authenticate, listSchedules);
router.post('/schedules', authenticate, authorize('ADMIN','DOCTOR','PATIENT'), [body('medicineName').trim().notEmpty(), body('dosage').trim().notEmpty(), body('times').isArray({ min:1 }), body('startDate').isISO8601()], validate, createSchedule);
router.patch('/schedules/:id', authenticate, authorize('ADMIN','DOCTOR','PATIENT'), updateSchedule);
router.delete('/schedules/:id', authenticate, authorize('ADMIN','DOCTOR','PATIENT'), deleteSchedule);
router.post('/schedules/:id/action', authenticate, authorize('ADMIN','DOCTOR','PATIENT'), scheduleAction);
router.get('/doses', authenticate, materializeToday, listDoses);
router.post('/doses/:id/action', authenticate, doseAction);
router.get('/reports/adherence', authenticate, adherence);
router.get('/doctors/patients', authenticate, authorize('DOCTOR'), myPatients);
router.post('/connections', authenticate, authorize('PATIENT'), connectPatient);
router.get('/admin/analytics', authenticate, authorize('ADMIN'), adminOverview);
router.get('/admin/users', authenticate, authorize('ADMIN'), adminUsers);
router.post('/admin/doctors/:id/approve', authenticate, authorize('ADMIN'), approveDoctor);
router.get('/medicines', authenticate, async (req,res,next)=>{ try { const data=await Medicine.find().sort({ medicineName:1 }); res.json({success:true,message:'Medicine catalog loaded',data}); } catch(e){next(e);} });
router.post('/medicines', authenticate, authorize('ADMIN'), async (req,res,next)=>{ try { const data=await Medicine.create({...req.body,createdBy:req.user.id}); res.status(201).json({success:true,message:'Medicine added to catalog',data}); } catch(e){next(e);} });
export default router;
